def copy(src, dst):
    if src.exists():
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        print(f"  copied  {dst.relative_to(DST)}")
    else:
        print(f"  MISSING {src}")


def main():
    for sub in ["isthmus", "docs", "figures", "experiments", "results"]:
        (DST / sub).mkdir(parents=True, exist_ok=True)
    print(f"building {DST}")
    pkg = SRC / "isthmus" / "__init__.py"
    copy(pkg if pkg.exists() else SRC / "gaptest.py", DST / "isthmus" / "__init__.py")
    copy(SRC / "pyproject.toml", DST / "pyproject.toml")
    for f in sorted((SRC / "docs").glob("*")):
        copy(f, DST / "docs" / f.name)
    for name in FIGURES:
        copy(SRC / "figures" / name, DST / "figures" / name)
    for name in SCRIPTS:
        copy(SRC / name, DST / "experiments" / name)
    for f in sorted(SRC.glob("*.csv")):
        copy(f, DST / "results" / f.name)
    for name, text in [(".gitignore", GITIGNORE), ("README.md", README), ("DATA.md", DATA), ("LICENSE", LICENSE)]:
        (DST / name).write_text(text, encoding="utf-8")
        print(f"  wrote   {name}")
    (DST / "isthmus" / "__main__.py").write_text(MAIN, encoding="utf-8")
    print("  wrote   isthmus/__main__.py")
    files = [p for p in DST.rglob("*") if p.is_file() and ".git" not in p.parts]
    print(f"\ndone: {len(files)} files, {sum(p.stat().st_size for p in files) / 1e6:.1f} MB in {DST}")


if __name__ == "__main__":
    main()